# Да се напише shell скрипт, който приема точно един параметър и проверява дали подаденият му параметър се състои само от букви и цифри.

#!/bin/bash

if [ "$#" -ne 1 ]; then
    echo "Трябва точно един параметър!"
    exit 1
fi

if [[ $1 =~ ^[a-zA-Z0-9]+$ ]]; then
    echo "Yes"
else
    echo "No"
fi
